CREATE OR REPLACE FUNCTION public.contractor_access_status()
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER
SET search_path=pg_catalog,public AS $fn$
  SELECT jsonb_build_object('is_admin',EXISTS(
    SELECT 1 FROM contractor_private.admin_memberships m
    WHERE m.user_id=auth.uid() AND m.active
  ));
$fn$;
REVOKE ALL ON FUNCTION public.contractor_access_status() FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.contractor_access_status() TO authenticated;

